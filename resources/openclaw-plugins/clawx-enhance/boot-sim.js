const path = require('node:path');
const fs = require('node:fs');

function mockFmt(msg, args) {
  if (!args || args.length === 0) return msg;
  let i = 0;
  return msg.replace(/%[sdjoO]/g, () => {
    const v = args[i++];
    return v === undefined ? 'undefined' : String(v);
  });
}

// ── 1) openclaw/plugin-sdk mock ──
// Real SDK lives in `openclaw/plugin-sdk`; the actual runtime injects the
// real impl. For boot-sim we provide a mock that records the registration
// and stubs the delegation with a no-op compaction.
let registeredEngines = new Map();
let delegationCalls = 0;
const mockSdk = {
  registerContextEngine(id, factory) {
    if (registeredEngines.has(id)) {
      return { ok: false, existingOwner: registeredEngines.get(id).info.id };
    }
    const engine = factory();
    registeredEngines.set(id, engine);
    return { ok: true, engine };
  },
  async delegateCompactionToRuntime(params) {
    delegationCalls += 1;
    // emulate "real" runtime — pretend a compaction happened
    return {
      ok: true,
      compacted: true,
      reason: 'delegated',
      result: {
        tokensBefore: params.currentTokenCount || 0,
        tokensAfter: 1000,
        summary: '[delegated summary — generated by openclaw runtime]',
      },
    };
  },
};

// ── 2) plugin api mock ──
function makeMockApi(pluginConfig = {}) {
  const handlers = new Map();
  return {
    id: 'clawx-enhance',
    name: 'clawx-enhance',
    version: '1.0.0',
    source: 'mock',
    rootDir: __dirname,
    config: {},
    pluginConfig,
    runtime: { llm: {} },
    logger: {
      debug: (msg, ...args) => args.length ? console.log('  [debug]', mockFmt(msg, args)) : console.log('  [debug]', msg),
      info:  (msg, ...args) => args.length ? console.log('  [info ]', mockFmt(msg, args)) : console.log('  [info ]', msg),
      warn:  (msg, ...args) => args.length ? console.log('  [warn ]', mockFmt(msg, args)) : console.log('  [warn ]', msg),
      error: (msg, ...args) => args.length ? console.log('  [error]', mockFmt(msg, args)) : console.log('  [error]', msg),
    },
    on: (event, handler) => {
      const list = handlers.get(event) || [];
      list.push(handler);
      handlers.set(event, list);
    },
    registerTool: () => {},
    registerHook: (events, handler) => {
      for (const e of [].concat(events)) {
        const list = handlers.get(e) || [];
        list.push(handler);
        handlers.set(e, list);
      }
    },
    registerHttpRoute: () => {},
    registerChannel: () => {},
    registerGatewayMethod: () => {},
    registerCli: () => {},
    registerService: () => {},
    _handlers: handlers,
    _fire: async (event, payload, ctx) => {
      const list = handlers.get(event) || [];
      const results = [];
      for (const h of list) {
        try {
          const r = await h(payload, ctx);
          if (r !== undefined) results.push(r);
        } catch (e) {
          results.push({ __error: e.message });
        }
      }
      return results;
    },
  };
}

(async () => {
  // ── Inject mock SDK via Module._resolveFilename ──
  // Real OpenClaw runtime injects the real `openclaw/plugin-sdk`. For
  // boot-sim we intercept the request and return a CJS shim that re-exports
  // our in-memory mock object via a `global` indirection.
  const Module = require('node:module');
  const origResolve = Module._resolveFilename;
  Module._resolveFilename = function (request, parent, ...rest) {
    if (request === 'openclaw/plugin-sdk') return path.join(__dirname, '.sdk-mock.cjs');
    return origResolve.call(this, request, parent, ...rest);
  };
  fs.writeFileSync(
    path.join(__dirname, '.sdk-mock.cjs'),
    `module.exports = global.__clawxPicoSdk;\n`,
  );
  global.__clawxPicoSdk = mockSdk;

  console.log('▶ Loading clawx-enhance plugin (mock boot, judgment-only engine)...');
  // OpenClaw loader converts `export default fn` to CJS; do the same here.
  const source = fs.readFileSync(path.join(__dirname, 'index.js'), 'utf8');
  const transformed = source.replace(/export\s+default\s+/g, 'module.exports.default = ');
  const tmpPath = path.join(__dirname, '.index.cjs.tmp');
  fs.writeFileSync(tmpPath, transformed, 'utf8');
  let pluginFn;
  try {
    const mod = require(tmpPath);
    pluginFn = mod.default || mod;
  } catch (e) {
    console.error('BOOT FAILED:', e.message);
    console.error(e.stack);
    process.exit(1);
  } finally {
    try { fs.unlinkSync(tmpPath); } catch {}
  }
  if (typeof pluginFn !== 'function') {
    console.error('plugin entry is not a function:', typeof pluginFn);
    process.exit(1);
  }

  const api = makeMockApi({});
  try {
    await pluginFn(api);
  } catch (e) {
    console.error('PLUGIN INIT THREW:', e.message, e.stack);
    process.exit(1);
  }
  console.log('✅ Plugin initialized without errors');

  // ── 1) ContextEngine registered ──
  if (!registeredEngines.has('clawx-pico')) {
    console.error('❌ clawx-pico ContextEngine NOT registered');
    process.exit(1);
  }
  const engine = registeredEngines.get('clawx-pico');
  console.log('✅ clawx-pico ContextEngine registered:', engine.info.name);

  // ── 2) Hooks registered ──
  const required = ['before_compaction', 'after_compaction'];
  for (const h of required) {
    if (!api._handlers.has(h)) {
      console.error(`❌ Missing required hook: ${h}`);
      process.exit(1);
    }
  }
  console.log('✅ observe hooks registered:', required.join(', '));

  // ── 3) compact() with low pressure → no-op ──
  console.log('\n▶ compact() @ 30% ratio, 10 msgs (should skip)...');
  const r1 = await engine.compact({
    sessionKey: 'boot:1',
    sessionId: 'boot:1',
    sessionFile: '/tmp/boot1.jsonl',
    messages: Array.from({ length: 10 }, (_, i) => ({ role: i % 2 ? 'assistant' : 'user', content: 'x' })),
    tokenBudget: 200_000,
    currentTokenCount: 60_000,
  });
  console.log('  →', r1);
  if (r1.compacted === false && /pico-skip/.test(r1.reason)) {
    console.log('✅ low pressure → no-op, delegate NOT called');
  } else {
    console.error('❌ unexpected low-pressure result:', r1);
    process.exit(1);
  }

  // ── 4) compact() with high pressure → delegate ──
  console.log('\n▶ compact() @ 90% ratio, 50 msgs (should delegate)...');
  const r2 = await engine.compact({
    sessionKey: 'boot:2',
    sessionId: 'boot:2',
    sessionFile: '/tmp/boot2.jsonl',
    messages: Array.from({ length: 50 }, (_, i) => ({ role: i % 2 ? 'assistant' : 'user', content: 'y'.repeat(2000) })),
    tokenBudget: 200_000,
    currentTokenCount: 180_000,
  });
  console.log('  →', r2);
  if (r2.compacted === true && delegationCalls === 1) {
    console.log('✅ high pressure → delegateCompactionToRuntime called, returned compacted=true');
  } else {
    console.error('❌ unexpected high-pressure result:', r2, 'delegationCalls=', delegationCalls);
    process.exit(1);
  }

  // ── 5) assemble / maintain are pass-through ──
  console.log('\n▶ assemble / maintain pass-through...');
  const a = await engine.assemble({ messages: [{ role: 'user', content: 'hello' }] });
  const m = await engine.maintain({ sessionFile: '/tmp/boot3.jsonl' });
  console.log('  assemble:', a);
  console.log('  maintain:', m);
  if (a.messages.length === 1 && m.changed === false) {
    console.log('✅ pass-through methods work');
  } else {
    console.error('❌ pass-through broken');
    process.exit(1);
  }

  // ── 6) before_compaction / after_compaction hooks don't throw ──
  console.log('\n▶ Fire before_compaction / after_compaction hooks...');
  await api._fire('before_compaction', { messageCount: 80, compactingCount: 30, tokenCount: 150_000 }, { sessionKey: 'boot:hook' });
  await api._fire('after_compaction',  { messageCount: 50, compactedCount: 30, tokenCount: 80_000 }, { sessionKey: 'boot:hook' });
  console.log('✅ observe hooks handled cleanly');

  // cleanup shim
  try { fs.unlinkSync(path.join(__dirname, '.sdk-mock.cjs')); } catch {}

  console.log('\n=== BOOT SIMULATION PASSED ===');
  process.exit(0);
})().catch((e) => {
  console.error('UNCAUGHT:', e);
  process.exit(1);
});
